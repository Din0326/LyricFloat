"""Generate the simplified/traditional character tables used for script detection.

    python tools/gen_char_tables.py

Runs every CJK ideograph through OpenCC once: characters that s2t changes
are "simplified", characters that t2s changes are "traditional-only".
Detection (SPEC v1.11) then needs no dictionary in memory. Re-run after
upgrading OpenCC. Output: src/lyricfloat/lyrics/char_tables.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import opencc

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "lyricfloat" / "lyrics" / "char_tables.py"
RANGES = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFF)]


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    s2t, t2s = opencc.OpenCC("s2t"), opencc.OpenCC("t2s")
    simplified, traditional = [], []
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            if s2t.convert(ch) != ch:
                simplified.append(ch)
            if t2s.convert(ch) != ch:
                traditional.append(ch)
    version = getattr(opencc, "__version__", "?")
    body = (
        '"""Generated by tools/gen_char_tables.py from OpenCC data (Apache-2.0); do not edit.\n\n'
        f"OpenCC {version}: {len(simplified)} characters changed by s2t, {len(traditional)} by t2s.\n"
        '"""\n\n'
        f"SIMPLIFIED = frozenset({''.join(simplified)!r})\n"
        f"TRADITIONAL_ONLY = frozenset({''.join(traditional)!r})\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"simplified {len(simplified)}, traditional-only {len(traditional)} -> {OUT} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
